#!/usr/bin/env node
/*
 * Regenerates src/content/legacy-inventory.ts: every public URL of the live
 * WordPress site that has an ID (pages, courses, instructors and the 272
 * attachment pages), read from its public REST API. Read-only: GET requests
 * only, no credentials. Run again before switch day so the redirect map
 * covers anything added since:
 *
 *   node scripts/legacy-inventory.mjs [https://ilmulquranus.org]
 *
 * Archives, feeds, sitemaps and the 404-log fixes are not in the REST API;
 * they are listed by hand in src/content/legacy-paths.ts.
 */
import { writeFileSync } from "node:fs";

const BASE = (process.argv[2] ?? "https://ilmulquranus.org").replace(/\/$/, "");
const HEADERS = { "user-agent": "Mozilla/5.0 (compatible; site-migration-inventory)" };

async function all(type, fields) {
  const out = [];
  for (let page = 1; ; page++) {
    const res = await fetch(`${BASE}/wp-json/wp/v2/${type}?per_page=100&page=${page}&_fields=${fields}`, { headers: HEADERS });
    if (res.status === 400 && page > 1) break; // past the last page
    if (!res.ok) throw new Error(`${type} page ${page}: HTTP ${res.status}`);
    const rows = await res.json();
    out.push(...rows);
    if (page >= Number(res.headers.get("x-wp-totalpages") ?? 1)) break;
  }
  return out;
}

/** "https://ilmulquranus.org/about/attachment/02/" → "/about/attachment/02"; "/?attachment_id=100" stays a query. */
function rel(link) {
  const url = new URL(link);
  const path = url.pathname.replace(/\/+$/, "") || "/";
  return url.search ? `${path}${url.search}` : path;
}

const content = [];
for (const [type, kind] of [["pages", "page"], ["ilm_ul_quran_course", "course"], ["iq_instructor", "instructor"]]) {
  for (const row of await all(type, "id,link")) content.push([row.id, kind, rel(row.link)]);
}
const media = (await all("media", "id,link,post")).map((m) => [m.id, rel(m.link), m.post ?? 0]);
content.sort((a, b) => a[0] - b[0]);
media.sort((a, b) => a[0] - b[0]);

const today = new Date().toISOString().slice(0, 10);
const file = `/*
 * GENERATED by scripts/legacy-inventory.mjs from ${BASE} on ${today}. Do not
 * edit by hand: run the script again. Read by src/content/legacy-paths.ts.
 */

export type LiveKind = "page" | "course" | "instructor";

/** [WordPress ID, kind, live path without the trailing slash] for every published page, course and instructor. */
export const liveContent: readonly (readonly [number, LiveKind, string])[] = [
${content.map((r) => `  [${r[0]}, "${r[1]}", "${r[2]}"],`).join("\n")}
];

/** [attachment ID, live attachment-page path (or "/?attachment_id=N"), parent post ID or 0]. */
export const liveAttachments: readonly (readonly [number, string, number])[] = [
${media.map((r) => `  [${r[0]}, "${r[1]}", ${r[2]}],`).join("\n")}
];
`;
writeFileSync(new URL("../src/content/legacy-inventory.ts", import.meta.url), file);
console.log(`${content.length} pages/courses/instructors, ${media.length} attachments`);
