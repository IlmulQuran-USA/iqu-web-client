#!/usr/bin/env node
/*
 * Regenerates src/content/sitemap-dates.ts: the sitemap's <lastmod> per route,
 * the date of the last commit that changed the files that render it. Built
 * from git here because a Vercel build may not have the history, and a build
 * date would tell search engines every page changed on every deploy.
 *
 *   node scripts/sitemap-dates.mjs        (run before switch day, and after content changes)
 *
 * A route listed with "/*" covers every page of a dynamic route.
 */
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const ROUTES = {
  "/": ["src/app/page.tsx", "src/content/home.ts", "src/content/home-hero.ts", "src/components/home"],
  "/about": ["src/app/about", "src/content/about.ts"],
  "/contact": ["src/app/contact", "src/content/contact.ts"],
  "/donate": ["src/app/donate", "src/content/donate.ts"],
  "/faq": ["src/app/faq", "src/content/faq.ts"],
  "/scholarship": ["src/app/scholarship", "src/content/scholarship.ts", "src/content/aid.ts"],
  "/courses": ["src/app/courses/page.tsx", "src/content/catalog.ts", "src/content/pricing.ts", "src/components/catalog"],
  "/instructors": ["src/app/instructors/page.tsx", "src/content/instructors-page.ts", "src/content/instructors.ts", "src/components/instructors/DirectorySections.tsx"],
  "/enroll": ["src/app/enroll/page.tsx", "src/components/enroll", "src/content/pricing.ts"],
  "/teach": ["src/app/teach", "src/content/teach.ts", "src/components/teach", "src/lib/teach"],
  "/courses/*": ["src/app/courses/[slug]", "src/content/courses.ts", "src/content/course-page.ts", "src/content/pricing.ts", "src/components/course"],
  "/programs/*": ["src/app/programs", "src/content/program-page.ts", "src/content/program-timetable.ts", "src/content/pricing.ts", "src/components/program"],
  "/instructors/*": ["src/app/instructors/[slug]", "src/content/instructors.ts", "src/content/instructors-page.ts", "src/components/instructors/ProfileSections.tsx"],
  "/legal/*": ["src/app/legal", "src/content/legal.ts", "src/components/legal"],
};

const dates = {};
for (const [route, files] of Object.entries(ROUTES)) {
  const out = execFileSync("git", ["log", "-1", "--format=%cs", "--", ...files], { encoding: "utf8" }).trim();
  // A route whose files are not committed yet (a new page): today, the day it is added.
  dates[route] = /^\d{4}-\d{2}-\d{2}$/.test(out) ? out : new Date().toISOString().slice(0, 10);
}

const file = `/*
 * GENERATED by scripts/sitemap-dates.mjs: the last commit that changed each
 * route's files. Do not edit by hand. Read by src/content/sitemap.ts.
 */
export const routeDates: Record<string, string> = ${JSON.stringify(dates, null, 2)};
`;
writeFileSync(new URL("../src/content/sitemap-dates.ts", import.meta.url), file);
console.log(dates);
